create function public.search_public_banks(search_term text default '',bank_type_filter text default '',limit_count integer default 50)
returns table(
  id uuid,
  name text,
  subject text,
  description text,
  bank_type text,
  uploader_username text,
  entry_count bigint,
  created_at timestamptz,
  updated_at timestamptz
)
language sql stable set search_path='' as $$
  select b.id,b.name,b.subject,b.description,b.bank_type,p.username,count(e.id)::bigint,b.created_at,b.updated_at
  from public.banks b
  join public.profiles p on p.id=b.owner_id
  left join public.bank_entries e on e.bank_id=b.id
  where b.visibility='public'
    and (coalesce(trim(bank_type_filter),'')='' or b.bank_type=trim(bank_type_filter))
    and (
      coalesce(trim(search_term),'')=''
      or b.name ilike '%'||trim(search_term)||'%'
      or b.subject ilike '%'||trim(search_term)||'%'
      or b.description ilike '%'||trim(search_term)||'%'
      or p.username ilike '%'||trim(search_term)||'%'
      or exists(
        select 1 from public.bank_entries se where se.bank_id=b.id and (
          coalesce(se.term,'') ilike '%'||trim(search_term)||'%'
          or coalesce(se.definition,'') ilike '%'||trim(search_term)||'%'
          or coalesce(se.question,'') ilike '%'||trim(search_term)||'%'
          or coalesce(se.explanation,'') ilike '%'||trim(search_term)||'%'
          or coalesce(se.choices::text,'') ilike '%'||trim(search_term)||'%'
        )
      )
    )
  group by b.id,p.username
  order by b.updated_at desc
  limit least(greatest(coalesce(limit_count,50),1),100);
$$;
grant execute on function public.search_public_banks(text,text,integer) to anon,authenticated;

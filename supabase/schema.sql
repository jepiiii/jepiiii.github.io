-- Explicit grants. Policies below still determine which rows are visible or mutable.
revoke all on table public.profiles from anon, authenticated;
revoke all on table public.banks from anon, authenticated;
revoke all on table public.bank_entries from anon, authenticated;

grant select on table public.profiles to anon, authenticated;
grant update on table public.profiles to authenticated;
grant select on table public.banks to anon, authenticated;
grant insert, update, delete on table public.banks to authenticated;
grant select on table public.bank_entries to anon, authenticated;
grant insert, update, delete on table public.bank_entries to authenticated;
grant usage, select on sequence public.bank_entries_id_seq to authenticated;

drop policy if exists "profiles are publicly readable" on public.profiles;
create policy "profiles are publicly readable"
on public.profiles for select
to anon, authenticated
using (true);

drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);


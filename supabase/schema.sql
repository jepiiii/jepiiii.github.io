on public.bank_entries for insert
to authenticated
with check (
  exists (
    select 1 from public.banks b
    where b.id = bank_entries.bank_id and b.owner_id = (select auth.uid())
  )
);

drop policy if exists "owners update bank entries" on public.bank_entries;

-- Enforce entry shape according to the parent bank type.
create or replace function public.validate_bank_entry()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_type text;
  choice_count integer;
  blank_choice_count integer;
begin
  select b.bank_type into parent_type from public.banks b where b.id = new.bank_id;
  if parent_type is null then raise exception 'Parent bank does not exist'; end if;

  if parent_type = 'typelearning' then
    if length(trim(coalesce(new.term,''))) = 0 or length(trim(coalesce(new.definition,''))) = 0 then
      raise exception 'TypeLearning entries require non-empty term and definition';
    end if;
    new.question := null;
    new.choices := null;
    new.correct_index := null;
    new.explanation := '';
  elsif parent_type = 'multiple_choice' then
    if length(trim(coalesce(new.question,''))) = 0 then raise exception 'MCQ entries require question text'; end if;
    if new.choices is null or jsonb_typeof(new.choices) <> 'array' then raise exception 'MCQ choices must be a JSON array'; end if;
    choice_count := jsonb_array_length(new.choices);
    if choice_count < 2 or choice_count > 6 then raise exception 'MCQ entries require 2 to 6 choices'; end if;
    select count(*) into blank_choice_count from jsonb_array_elements_text(new.choices) c(value) where length(trim(c.value)) = 0;
    if blank_choice_count > 0 then raise exception 'MCQ choices cannot be blank'; end if;
    if new.correct_index is null or new.correct_index < 0 or new.correct_index >= choice_count then raise exception 'MCQ correct_index is out of range'; end if;
    new.term := null;
    new.definition := null;
    new.explanation := coalesce(new.explanation,'');
  else
    raise exception 'Unsupported bank type: %', parent_type;
  end if;
  return new;
end;
$$;


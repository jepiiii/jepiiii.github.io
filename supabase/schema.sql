create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare requested text; candidate text;
begin
  requested := coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'),''),split_part(coalesce(new.email,''),'@',1),'user');
  candidate := lower(regexp_replace(requested,'[^A-Za-z0-9_.-]+','','g'));
  if char_length(candidate) < 3 then candidate := 'user_' || substr(new.id::text,1,6); end if;
  candidate := left(candidate,32);
  if exists(select 1 from public.profiles p where lower(p.username)=lower(candidate)) then candidate := left(candidate,24) || '_' || substr(new.id::text,1,6); end if;
  insert into public.profiles(id,username) values(new.id,candidate) on conflict(id) do nothing;
  return new;
end;
$$;

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_length check (char_length(username) between 3 and 32),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9_][A-Za-z0-9_.-]*$')
);
create unique index if not exists profiles_username_lower_uidx on public.profiles (lower(username));

create table if not exists public.banks (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  subject text not null default '',
  description text not null default '',
  visibility text not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint banks_name_length check (char_length(name) between 1 and 120),
  constraint banks_subject_length check (char_length(subject) <= 120),
  constraint banks_description_length check (char_length(description) <= 1000),
  constraint banks_visibility_check check (visibility in ('public','private'))
);
create index if not exists banks_owner_id_idx on public.banks(owner_id);
create index if not exists banks_visibility_updated_idx on public.banks(visibility, updated_at desc);
create index if not exists banks_name_lower_idx on public.banks(lower(name));
create index if not exists banks_subject_lower_idx on public.banks(lower(subject));

create table if not exists public.bank_entries (
  id bigint generated by default as identity primary key,
  bank_id uuid not null references public.banks(id) on delete cascade,
  position integer not null default 0,
  term text not null,
  definition text not null,
  created_at timestamptz not null default now(),
  constraint bank_entries_term_nonempty check (length(trim(term)) > 0),
  constraint bank_entries_definition_nonempty check (length(trim(definition)) > 0)
);
create index if not exists bank_entries_bank_id_idx on public.bank_entries(bank_id);
create unique index if not exists bank_entries_bank_position_uidx on public.bank_entries(bank_id, position);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists banks_set_updated_at on public.banks;
create trigger banks_set_updated_at
before update on public.banks
for each row execute function public.set_updated_at();

create schema if not exists private;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested text;
  candidate text;
begin
  requested := coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), split_part(coalesce(new.email, ''), '@', 1), 'user');
  candidate := lower(regexp_replace(requested, '[^A-Za-z0-9_.-]+', '', 'g'));
  if char_length(candidate) < 3 then candidate := 'user_' || substr(new.id::text, 1, 6); end if;
  candidate := left(candidate, 32);
  if exists (select 1 from public.profiles p where lower(p.username) = lower(candidate)) then
    candidate := left(candidate, 24) || '_' || substr(new.id::text, 1, 6);
  end if;
  insert into public.profiles(id, username) values (new.id, candidate)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();


create or replace function public.merge_bank_progress_batch(p_bank_id uuid,p_records jsonb)
returns void language plpgsql security invoker set search_path='' as $$
declare item jsonb;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  for item in select elem from jsonb_array_elements(coalesce(p_records,'[]'::jsonb)) as t(elem) loop
    insert into public.user_bank_progress(user_id,bank_id,entry_fingerprint,encounter_count,correct_count,incorrect_count,revealed_count,last_encountered_at)
    values(auth.uid(),p_bank_id,item->>'entry_fingerprint',greatest(coalesce((item->>'encounter_count')::integer,0),0),greatest(coalesce((item->>'correct_count')::integer,0),0),greatest(coalesce((item->>'incorrect_count')::integer,0),0),greatest(coalesce((item->>'revealed_count')::integer,0),0),nullif(item->>'last_encountered_at','')::timestamptz)
    on conflict(user_id,bank_id,entry_fingerprint) do update set
      encounter_count=greatest(public.user_bank_progress.encounter_count,excluded.encounter_count),
      correct_count=greatest(public.user_bank_progress.correct_count,excluded.correct_count),
      incorrect_count=greatest(public.user_bank_progress.incorrect_count,excluded.incorrect_count),
      revealed_count=greatest(public.user_bank_progress.revealed_count,excluded.revealed_count),
      last_encountered_at=greatest(public.user_bank_progress.last_encountered_at,excluded.last_encountered_at);
  end loop;
end;
$$;


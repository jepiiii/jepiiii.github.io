-- Atomic progress increment. Security invoker means RLS still applies.
create or replace function public.record_bank_progress(
  p_bank_id uuid,
  p_entry_fingerprint text,
  p_encounter_delta integer default 0,
  p_correct_delta integer default 0,
  p_incorrect_delta integer default 0,
  p_revealed_delta integer default 0,
  p_last_encountered_at timestamptz default null
)
returns void language plpgsql security invoker set search_path='' as $$
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  insert into public.user_bank_progress(user_id,bank_id,entry_fingerprint,encounter_count,correct_count,incorrect_count,revealed_count,last_encountered_at)
  values(auth.uid(),p_bank_id,p_entry_fingerprint,greatest(p_encounter_delta,0),greatest(p_correct_delta,0),greatest(p_incorrect_delta,0),greatest(p_revealed_delta,0),p_last_encountered_at)
  on conflict(user_id,bank_id,entry_fingerprint) do update set
    encounter_count=public.user_bank_progress.encounter_count+greatest(excluded.encounter_count,0),
    correct_count=public.user_bank_progress.correct_count+greatest(excluded.correct_count,0),
    incorrect_count=public.user_bank_progress.incorrect_count+greatest(excluded.incorrect_count,0),
    revealed_count=public.user_bank_progress.revealed_count+greatest(excluded.revealed_count,0),
    last_encountered_at=coalesce(excluded.last_encountered_at,public.user_bank_progress.last_encountered_at);
end;
$$;


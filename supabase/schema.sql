on public.banks for select
to anon, authenticated
using (visibility = 'public' or owner_id = (select auth.uid()));

drop policy if exists "users create own banks" on public.banks;
create policy "users create own banks"
on public.banks for insert
to authenticated
with check (owner_id = (select auth.uid()));

drop policy if exists "owners update banks" on public.banks;
create policy "owners update banks"
on public.banks for update
to authenticated
using (owner_id = (select auth.uid()))
with check (owner_id = (select auth.uid()));

drop policy if exists "owners delete banks" on public.banks;
create policy "owners delete banks"
on public.banks for delete
to authenticated
using (owner_id = (select auth.uid()));

drop policy if exists "public bank entries readable or owner readable" on public.bank_entries;
